return function(test, eq, contains)
  local function configured(f)
    return f.client({
      no_session = true,
      default_selection = { provider = "openai", model = "reasoner", thinking = "medium" },
    })
  end

  local function submit(f, client, opts)
    local run = { chunks = {}, completions = 0 }
    local accepted, err = client.prompt("question", function(chunk)
      table.insert(run.chunks, chunk)
    end, function(text, rpc_err, metadata)
      run.completions = run.completions + 1
      run.text = text
      run.error = rpc_err
      run.metadata = metadata
    end, opts)
    assert(accepted, err)
    f.flush()
    return run
  end

  test("cancelling during preparation skips the prompt and restores one-shot settings without a restart", function(f)
    local client = configured(f)
    f.hold.get_state = true
    local run = submit(f, client)
    eq(client.status().phase, "starting")
    eq(client.status().kind, "prompt")
    assert(client.abort())
    assert(client.abort())
    eq(client.status().phase, "cancelling")
    eq(client.is_busy(), true)
    f.hold.get_state = nil
    assert(f.release("get_state"))
    f.wait(function() return run.completions == 1 end)
    eq(run.metadata.status, "aborted")
    eq(run.error, "Pi request aborted")
    eq(#f.sent, 0)
    eq(f.count("abort"), 0)
    eq(f.jobs[1].stopped, nil)
    eq(client.is_busy(), false)
    eq(client.status().phase, "idle")
    f.hold.set_model = true
    local big = submit(f, client, { override = { model = "anthropic/large", thinking = "max" } })
    f.wait(function() return #f.held == 1 end)
    assert(client.abort())
    f.hold.set_model = nil
    assert(f.release("set_model"))
    f.wait(function() return big.completions == 1 end)
    eq(big.metadata.status, "aborted")
    eq(#f.sent, 0)
    eq(client.state.model.id, "reasoner")
    eq(client.state.thinking_level, "medium")
    eq(client.get_restore_selection(), nil)
    local normal = submit(f, client)
    f.complete(1)
    eq(normal.metadata.status, "complete")
    eq(normal.metadata.models[1], { provider = "openai", model = "reasoner", thinking = "medium" })
    eq(#f.jobs, 1)
  end)

  test("cancelling during generation aborts through Pi and keeps the partial text and process", function(f)
    local client = configured(f)
    local run = submit(f, client)
    f.start_message(1)
    f.text(1, "partial answer")
    f.flush()
    eq(client.status().phase, "generating")
    assert(client.abort())
    f.wait(function() return run.completions == 1 end)
    eq(run.text, "partial answer")
    eq(run.metadata.status, "aborted")
    eq(run.error, "Pi request aborted")
    eq(f.count("abort"), 1)
    eq(f.jobs[1].stopped, nil)
    eq(client.is_busy(), false)
    local ok, err = client.abort()
    eq(ok, false)
    eq(err, "Nothing is running.")
    local next_run = submit(f, client)
    f.complete(1)
    eq(next_run.metadata.status, "complete")
    eq(#f.jobs, 1)
  end)

  test("repeated cancellation sends one abort and settings or restoration work cannot be cancelled", function(f)
    local client = configured(f)
    f.hold.get_available_models = true
    local listed
    assert(client.get_available_models(function(items, err) listed = { items, err } end))
    f.wait(function() return #f.held == 1 end)
    local ok, err = client.abort()
    eq(ok, false)
    contains(err, "cannot be cancelled")
    eq(client.status().phase, "starting")
    eq(client.status().kind, "listing")
    f.hold.get_available_models = nil
    assert(f.release("get_available_models"))
    f.wait(function() return listed ~= nil end)
    eq(#listed[1], 4)
    local run = submit(f, client)
    f.start_message(1)
    f.flush()
    f.hold.abort = true
    assert(client.abort())
    assert(client.abort())
    f.wait(function() return #f.held == 1 end)
    eq(f.count("abort"), 1)
    eq(client.status().phase, "cancelling")
    eq(run.completions, 0)
    f.hold.abort = nil
    assert(f.release("abort"))
    f.wait(function() return run.completions == 1 end)
    eq(run.metadata.status, "aborted")
    eq(f.count("abort"), 1)
    local big = submit(f, client, { override = { model = "anthropic/large", thinking = "max" } })
    eq(f.sent[#f.sent].model.id, "large")
    f.hold.set_model = true
    f.complete(1, "big answer")
    f.wait(function() return #f.held == 1 end)
    eq(big.completions, 0)
    eq(client.status().phase, "finishing")
    ok, err = client.abort()
    eq(ok, false)
    contains(err, "cannot be cancelled")
    f.hold.set_model = nil
    assert(f.release("set_model"))
    f.wait(function() return big.completions == 1 end)
    eq(big.metadata.status, "complete")
    eq(big.text, "big answer")
    eq(client.state.model.id, "reasoner")
    eq(f.count("abort"), 1)
    eq(#f.jobs, 1)
  end)

  test("status is a local snapshot of phase, elapsed time, and tools that is cleared at settlement", function(f)
    local idle = f.client()
    eq(idle.status(), { phase = "idle", ready = false, tools = {} })
    local client = configured(f)
    eq(client.status().model.id, "reasoner")
    eq(client.status().thinking, "medium")
    f.clock = 1000000000
    local run = submit(f, client)
    f.start_message(1)
    f.clock = 1500000000
    f.emit(1, { type = "tool_execution_start", toolCallId = "call-1", toolName = "bash", args = { command = "ls -la" } })
    f.flush()
    f.clock = 2500000000
    local before = #f.commands
    local status = client.status()
    eq(#f.commands, before)
    eq(status.phase, "tool")
    eq(status.elapsed_ms, 1500)
    eq(#status.tools, 1)
    eq(status.tools[1].name, "bash")
    eq(status.tools[1].arg, "ls -la")
    eq(status.tools[1].elapsed_ms, 1000)
    eq(status.tools[1].partial, nil)
    f.emit(1, { type = "tool_execution_update", toolCallId = "other", toolName = "bash", partialResult = { content = {} } })
    f.emit(1, { type = "tool_execution_update", toolCallId = "call-1", toolName = "bash", args = { command = "ls -la" }, partialResult = { content = { { type = "text", text = "partial output" } } } })
    f.flush()
    eq(client.status().tools[1].partial.content[1].text, "partial output")
    f.emit(1, { type = "tool_execution_end", toolCallId = "call-1", toolName = "bash", result = { content = {} }, isError = false })
    f.flush()
    eq(client.status().phase, "generating")
    eq(client.status().tools, {})
    f.emit(1, { type = "tool_execution_start", toolCallId = "call-2", toolName = "read", args = { path = "file.lua" } })
    f.emit(1, { type = "compaction_start", reason = "threshold" })
    f.flush()
    eq(client.status().phase, "compacting")
    f.emit(1, { type = "compaction_end", aborted = false })
    f.flush()
    eq(client.status().phase, "tool")
    eq(client.status().tools[1].arg, "file.lua")
    assert(client.abort())
    f.wait(function() return run.completions == 1 end)
    eq(client.status().phase, "idle")
    eq(client.status().tools, {})
    eq(client.status().elapsed_ms, nil)
    eq(#f.jobs, 1)
  end)

  test("subagent progress comes only from tool updates and renders with the rest of the status", function(f)
    local operation = require("mentat.operation")
    eq(operation.render({ phase = "idle", tools = {}, model = { provider = "openai", id = "reasoner" }, thinking = "medium" }, "Mentat"),
      "Mentat: Idle | Model: openai/reasoner | Thinking: medium")
    eq(operation.render({ phase = "generating", elapsed_ms = 65000, tools = {} }, "Mentat branch"), "Mentat branch: Generating | Elapsed: 1m 05s")
    local long = string.rep("x", 100)
    contains(operation.render({ phase = "tool", elapsed_ms = 1200, tools = { { name = "bash", arg = long } } }, "Mentat"),
      "Running tool | Elapsed: 1.2s | Tool: bash: " .. string.rep("x", 57) .. "...")
    local client = configured(f)
    local run = submit(f, client)
    f.start_message(1)
    f.emit(1, { type = "tool_execution_start", toolCallId = "sub-1", toolName = "subagent", args = { agent = "programmer", task = "fix it" } })
    f.flush()
    eq(run.chunks[1], "\n\n> *subagent: programmer*\n\n")
    local text = operation.render(client.status(), "Mentat")
    contains(text, "Mentat: Running tool | Elapsed: ")
    contains(text, "Tool: subagent: programmer")
    contains(text, "Subagent progress is unavailable.")
    f.emit(1, { type = "tool_execution_update", toolCallId = "sub-1", toolName = "subagent", args = {}, partialResult = {
      content = { { type = "text", text = "(running...)" } },
      details = { mode = "single", results = { { agent = "programmer", exitCode = -1, usage = { turns = 2 } } } },
    } })
    f.flush()
    text = operation.render(client.status(), "Mentat")
    contains(text, "\nprogrammer: running (2 turns)")
    eq(text:find("unavailable", 1, true), nil)
    f.emit(1, { type = "tool_execution_update", toolCallId = "sub-1", toolName = "subagent", args = {}, partialResult = {
      content = { { type = "text", text = "Parallel: 1/2 done, 1 running..." } },
      details = { mode = "parallel", results = {
        { agent = "first", exitCode = 0, usage = { turns = 1 } },
        { agent = "second", exitCode = -1, usage = { turns = 0 } },
      } },
    } })
    f.flush()
    text = operation.render(client.status(), "Mentat")
    contains(text, "\nfirst: done (1 turn)\nsecond: running")
    f.emit(1, { type = "tool_execution_update", toolCallId = "sub-1", toolName = "subagent", partialResult = { content = {}, details = { results = "invalid" } } })
    f.flush()
    contains(operation.render(client.status(), "Mentat"), "Subagent progress is unavailable.")
    f.text(1, "done")
    f.finish(1, "done")
    f.flush()
    eq(run.completions, 1)
    eq(client.status().tools, {})
    eq(operation.render(client.status(), "Mentat"), "Mentat: Idle | Model: openai/reasoner | Thinking: medium")
  end)

  test("Cancel and Status commands act on the focused conversation without starting Pi", function(f)
    local mentat, buffer = f.ui()
    eq(vim.fn.maparg("<leader>mx", "n"), "<Cmd>MentatCancel<CR>")
    eq(vim.fn.maparg("<leader>mi", "n"), "<Cmd>MentatStatus<CR>")
    vim.cmd("MentatStatus")
    eq(f.notices[#f.notices].message, "Mentat: Idle")
    vim.cmd("MentatCancel")
    eq(f.notices[#f.notices].message, "Nothing is running.")
    eq(#f.jobs, 0)
    eq(vim.fn.bufnr("Mentat"), -1)
    buffer.open()
    local client = mentat.get_client()
    f.wait(function() return client.state.ready and not client.is_busy() end)
    local buf = buffer.target().bufnr
    f.draft(buf, "cancel me")
    f.press(buf, "<CR>")
    f.wait(function() return #f.sent == 1 end)
    f.start_message(1)
    f.text(1, "partial answer")
    f.flush()
    f.draft(buf, "next draft")
    vim.cmd("MentatStatus")
    contains(f.notices[#f.notices].message, "Mentat: Generating | Elapsed: ")
    contains(f.notices[#f.notices].message, "Model: openai/reasoner | Thinking: medium")
    vim.cmd("MentatCancel")
    eq(f.notices[#f.notices].message, "Cancellation requested.")
    f.wait(function() return not client.is_busy() end)
    local text = f.content(buf)
    contains(text, "partial answer")
    contains(text, "**Aborted:** Pi request aborted")
    contains(text, "[Status: aborted - First text:")
    eq(text:sub(-#"next draft"), "next draft")
    eq(f.jobs[1].stopped, nil)
    local path = f.root .. "/.mentat/logs/" .. os.date("%Y-%m-%d") .. ".md"
    local function log()
      return vim.fn.filereadable(path) == 1 and table.concat(vim.fn.readfile(path), "\n") or ""
    end
    f.wait(function() return log():find("partial answer", 1, true) ~= nil end)
    contains(log(), "Status: aborted")
    f.press(buf, "<CR>")
    f.wait(function() return #f.sent == 2 end)
    contains(f.sent[2].message, "next draft")
    f.complete(1)
    eq(#f.jobs, 1)
    local branch = require("mentat.branch").open("branch question")
    local picker = require("mentat.model_picker")
    f.wait(function()
      local target = picker.target(branch)
      return target.client and not target.client.is_busy()
    end)
    f.press(branch, "<CR>")
    f.wait(function() return #f.sent == 3 end)
    eq(f.sent[3].job, 2)
    f.start_message(2)
    f.flush()
    vim.api.nvim_set_current_buf(buf)
    vim.cmd("MentatStatus")
    eq(f.notices[#f.notices].message, "Mentat: Idle | Model: openai/reasoner | Thinking: medium")
    vim.api.nvim_set_current_buf(branch)
    vim.cmd("MentatStatus")
    contains(f.notices[#f.notices].message, "Mentat branch: Generating | Elapsed: ")
    vim.cmd("MentatCancel")
    eq(f.notices[#f.notices].message, "Cancellation requested.")
    f.wait(function() return not picker.target(branch).client.is_busy() end)
    eq(f.commands[#f.commands - 2].command.type, "abort")
    eq(f.commands[#f.commands - 2].job, 2)
    contains(f.content(branch), "**Aborted:** Pi request aborted")
    eq(client.is_busy(), false)
    eq(f.jobs[1].stopped, nil)
    eq(f.jobs[2].stopped, nil)
  end)
end
