  test("branches inherit chosen settings, change independently, and capture picker targets", function(f)
    local mentat, buffer, main, _, editor_win = opened(f)
    local client = mentat.get_client()
    assert(f.await(function(done) return client.set_model("anthropic", "legacy", done) end))
    assert(f.await(function(done) return client.set_thinking_level("low", done) end))
    f.draft(main, "main history")
    f.press(main, "<CR>")
    f.wait(function() return #f.sent == 1 end)
    f.complete(1)
    local branch = require("mentat.branch").open("branch question")
    local picker_module = require("mentat.model_picker")
    f.wait(function()
      local target = picker_module.target(branch)
      return target.client and not target.client.is_busy()
    end)
    local branch_client = picker_module.target(branch).client
    eq(branch_client.get_selection(), client.get_selection())
    eq(branch_client.state.session_file == mentat.get_session_file(), false)
    f.press(branch, "<CR>")
    f.wait(function() return #f.sent == 2 end)
    eq(f.sent[2].job, 2)
    eq(f.sent[2].model.id, "legacy")
    eq(f.sent[2].thinking, "low")
    f.complete(2)
    local picker = f.picker("MentatModel")
    picker.choose(model_item(picker, "plain"))
    f.wait(function() return not branch_client.is_busy() end)
    eq(branch_client.state.model.id, "plain")
    eq(branch_client.state.thinking_level, "off")
    eq(client.state.model.id, "legacy")
    picker = f.picker("MentatThinking")
    eq(picker.items, { "off" })
    picker.choose(nil)
    vim.api.nvim_set_current_win(editor_win)
    picker = f.picker("MentatModel")
    vim.api.nvim_set_current_buf(branch)
    picker.choose(model_item(picker, "reasoner"))
    f.wait(function() return not client.is_busy() end)
    eq(client.state.model.id, "reasoner")
    eq(branch_client.state.model.id, "plain")
    vim.cmd("MentatPromote")
    f.wait(function() return #f.sent == 3 end)
    eq(f.sent[3].job, 2)
    eq(f.sent[3].model.id, "large")
    f.complete(2)
    eq(branch_client.state.model.id, "plain")
    eq(branch_client.state.thinking_level, "off")
    eq(client.state.model.id, "reasoner")
    eq(#f.jobs, 2)
    contains(f.content(branch), "## Pi\n")
    eq(f.content(branch):find("## Pi (", 1, true), nil)
    eq(buffer.target().bufnr, main)
  end)

  test("closing a starting branch preserves its draft and cancels startup work", function(f)
    local mentat = f.ui()
    f.hold.get_state = true
    local branch = require("mentat.branch").open("keep this draft")
    local before = f.content(branch)
    f.press(branch, "<CR>")
    eq(f.content(branch), before)
    local called = false
    vim.ui.select = function() called = true end
    vim.cmd("MentatModel")
    eq(called, false)
    f.flush()
    vim.api.nvim_buf_delete(branch, { force = true })
    f.hold.get_state = nil
    assert(f.release("get_state"))
    f.wait(function() return not mentat.get_client().is_busy() end)
    eq(#f.jobs, 1)
    eq(#f.sent, 0)
    eq(vim.api.nvim_buf_is_loaded(branch), false)
  end)

  test("cancelled and stale picker callbacks cannot change settings or erase a draft", function(f)
    local mentat, buffer, buf = opened(f)
    local picker = f.picker("MentatModel")
    local from = #f.commands + 1
    picker.choose(nil)
    f.flush()
    eq(f.count("set_model", from), 0)
    picker = f.picker("MentatModel")
    f.draft(buf, "send while picker is open")
    f.press(buf, "<CR>")
    local before = f.content(buf)
    picker.choose(model_item(picker, "large"))
    eq(f.content(buf), before)
    f.wait(function() return #f.sent == 1 end)
    eq(f.sent[1].model.id, "reasoner")
    f.complete(1)
    picker = f.picker("MentatThinking")
    local saved = f.seed(f.catalog[4], "low")
    assert(f.await(function(done) return mentat.switch_session(saved, done) end))
    from = #f.commands + 1
    picker.choose("high")
    f.flush()
    eq(f.count("set_thinking_level", from), 0)
    eq(mentat.get_client().state.thinking_level, "low")
    picker = f.picker("MentatModel")
    from = #f.commands + 1
    buffer.close()
    picker.choose(model_item(picker, "large"))
    f.flush()
    eq(f.count("set_model", from), 0)
    buffer.open()
    f.wait(function() return not mentat.get_client().is_busy() end)
    picker = f.picker("MentatModel")
    vim.api.nvim_buf_delete(buf, { force = true })
    from = #f.commands + 1
    picker.choose(model_item(picker, "large"))
    f.flush()
    eq(f.count("set_model", from), 0)
    eq(vim.api.nvim_buf_is_loaded(buf), false)
    eq(mentat.get_client().is_busy(), false)
  end)

