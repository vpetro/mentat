return function(test, eq, contains)
  local function opened(f, config)
    local mentat, buffer, editor = f.ui(config)
    local editor_win = vim.api.nvim_get_current_win()
    buffer.open()
    local client = mentat.get_client()
    f.wait(function() return client.state.ready and not client.is_busy() end)
    return mentat, buffer, buffer.target().bufnr, editor, editor_win
  end

  local function model_item(picker, id)
    for _, item in ipairs(picker.items) do
      if item.id == id then
        return item
      end
    end
    error("Model not in picker: " .. id)
  end

  test("response text uses a plain header and one compact status and timestamp line", function(f)
    local _, _, buf = opened(f)
    local body = "Hi Petro. What are we working on?"
    f.clock = 1000000000
    f.draft(buf, "hi there")
    f.press(buf, "<CR>")
    f.wait(function() return #f.sent == 1 end)
    f.start_message(1)
    f.clock = 2640000000
    f.text(1, body)
    f.flush()
    f.clock = 4250000000
    f.finish(1, body .. "\n\n[2026-09-12 03:07:57 Sat EDT (UTC-04:00)]")
    f.flush()
    local text = f.content(buf)
    local header = assert(text:find("## Pi", 1, true))
    eq(text:sub(header), table.concat({
      "## Pi", body, "",
      "[Status - First text: 1.64s | Total: 3.25s] - [2026-09-12 03:07:57]",
      "---", "",
    }, "\n"))
    local log = table.concat(vim.fn.readfile(f.root .. "/.mentat/logs/" .. os.date("%Y-%m-%d") .. ".md"), "\n")
    contains(log, "### Pi (openai/reasoner; thinking medium)")
    contains(log, "[Status - First text: 1.64s | Total: 3.25s] - [2026-09-12 03:07:57]\n---")
  end)

  test("main Enter uses defaults, then the selected combination on successive sends", function(f)
    local mentat, buffer, buf, _, editor_win = opened(f)
    local config = vim.deepcopy(mentat.config)
    contains(vim.wo.winbar, "openai/reasoner; thinking medium")
    eq(vim.api.nvim_get_option_value("winbar", { win = editor_win, scope = "local" }), "editor winbar")
    f.draft(buf, "first question")
    f.press(buf, "<CR>")
    f.wait(function() return #f.sent == 1 end)
    f.complete(1)
    eq(f.sent[1].model.id, "reasoner")
    eq(f.sent[1].thinking, "medium")
    contains(f.content(buf), "## Pi\n")
    eq(f.content(buf):find("## Pi (", 1, true), nil)
    contains(f.content(buf), "First text:")
    local picker = f.picker("MentatModel")
    eq(picker.options.kind, "mentat_model")
    contains(picker.options.format_item(model_item(picker, "reasoner")), "* openai/reasoner")
    contains(picker.options.format_item(model_item(picker, "legacy")), "quick: Quick / low")
    picker.choose(model_item(picker, "legacy"))
    f.wait(function() return not mentat.get_client().is_busy() end)
    picker = f.picker("MentatThinking")
    eq(picker.options.kind, "mentat_thinking")
    contains(picker.options.format_item("medium"), "* medium")
    picker.choose("low")
    f.wait(function() return not mentat.get_client().is_busy() end)
    local from = #f.commands + 1
    for index = 2, 3 do
      f.draft(buf, "question " .. index)
      f.press(buf, "<CR>")
      f.wait(function() return #f.sent == index end)
      f.complete(1)
      eq(f.sent[index].model.id, "legacy")
      eq(f.sent[index].thinking, "low")
    end
    eq(f.count("set_model", from), 0)
    eq(f.count("set_thinking_level", from), 0)
    eq(#f.jobs, 1)
    eq(mentat.config, config)
    local log = table.concat(vim.fn.readfile(f.root .. "/.mentat/logs/" .. os.date("%Y-%m-%d") .. ".md"), "\n")
    contains(log, "### Pi (anthropic/legacy; thinking low)")
    contains(log, "Total:")
    contains(log, "[Status - First text:")
    eq(log:find("Status: complete", 1, true), nil)
    assert(buffer.clear())
    f.wait(function() return not mentat.get_client().is_busy() end)
    eq(mentat.get_client().get_selection(), { provider = "openai", model = "reasoner", thinking = "medium" })
    eq(f.content(buf), "# Mentat Chat\n")
    contains(vim.wo.winbar, "openai/reasoner; thinking medium")
  end)

  test("response headers stay above streamed text without a repeated model footer", function(f)
    local _, _, buf = opened(f)
    f.draft(buf, "question")
    f.press(buf, "<CR>")
    f.wait(function() return #f.sent == 1 end)
    f.start_message(1)
    f.text(1, "First line.")
    f.flush()
    local text = f.content(buf)
    local header = assert(text:find("## Pi\n", 1, true))
    local body = assert(text:find("First line.", 1, true))
    assert(header < body)
    f.text(1, "\n\nSecond line.")
    f.finish(1, "First line.\n\nSecond line.")
    f.flush()
    text = f.content(buf)
    contains(text, "First line.\n\nSecond line.")
    local _, headers = text:gsub("## Pi\n", "")
    eq(headers, 1)
    assert(text:find("## Pi\n", 1, true) < text:find("First line.", 1, true))
  end)

  test("timing precedes the final timestamp in the main response and log without changing the draft", function(f)
    local _, _, buf = opened(f)
    local body = "First line.\n\nSecond line."
    local stamp = "[2026-09-12 02:57:52 Sat EDT (UTC-04:00)]"
    local short_stamp = "[2026-09-12 02:57:52]"
    f.draft(buf, "question")
    f.press(buf, "<CR>")
    f.wait(function() return #f.sent == 1 end)
    f.start_message(1)
    f.text(1, body)
    f.flush()
    f.draft(buf, "next draft")
    f.finish(1, body .. "\n\n" .. stamp)
    f.flush()
    local text = f.content(buf)
    local timing = assert(text:find("[Status - First text:", 1, true))
    local timestamp, last = text:find(short_stamp, 1, true)
    assert(timestamp and timing < timestamp)
    eq(text:find(stamp, 1, true), nil)
    contains(text, body)
    eq(text:sub(last + 1), "\n---\nnext draft")
    local log = table.concat(vim.fn.readfile(f.root .. "/.mentat/logs/" .. os.date("%Y-%m-%d") .. ".md"), "\n")
    assert(log:find("[Status - First text:", 1, true) < log:find(short_stamp, 1, true))
    assert(log:sub(select(2, log:find(short_stamp, 1, true)) + 1):match("^\n%-%-%-%s*$"))
  end)

  test("response formatting keeps errors before timestamps and leaves other date text alone", function()
    local response = require("mentat.response")
    local stamp = "[2026-09-12 02:57:52 Sat EDT (UTC-04:00)]"
    local short_stamp = "[2026-09-12 02:57:52]"
    for _, status in ipairs({ "error", "aborted" }) do
      local metadata = { first_text_ms = 125, total_ms = 3000, status = status }
      local label = status == "aborted" and "Aborted" or "Error"
      eq(response.timing(metadata), "[Status: " .. status .. " - First text: 125ms | Total: 3.00s]")
      eq(response.body("Partial text.\n\n" .. stamp .. "\n\n", metadata, "Stopped"),
        "Partial text.\n\n**" .. label .. ":** Stopped\n\n" .. response.timing(metadata) .. " - " .. short_stamp)
    end
    local metadata = { total_ms = 3000, status = "complete" }
    eq(response.body(stamp, metadata), response.timing(metadata) .. " - " .. short_stamp)
    for _, body in ipairs({ "No timestamp.", "Discuss " .. stamp, "```\n" .. stamp .. "\n```" }) do
      eq(response.body(body, metadata), body .. "\n\n" .. response.timing(metadata))
    end
  end)

  test("branch responses keep one header and put timing before a streamed timestamp", function(f)
    opened(f)
    local buf = require("mentat.branch").open("branch question")
    local picker = require("mentat.model_picker")
    f.wait(function()
      local target = picker.target(buf)
      return target.client and not target.client.is_busy()
    end)
    f.press(buf, "<CR>")
    f.wait(function() return #f.sent == 1 end)
    local stamp = "[2026-09-12 02:57:52 Sat EDT (UTC-04:00)]"
    local short_stamp = "[2026-09-12 02:57:52]"
    f.complete(2, "Branch answer.\n\n" .. stamp)
    local text = f.content(buf)
    contains(text, "Branch answer.")
    local _, headers = text:gsub("## Pi\n", "")
    eq(headers, 1)
    assert(text:find("[Status - First text:", 1, true) < text:find(short_stamp, 1, true))
    eq(text:sub(select(2, text:find(short_stamp, 1, true)) + 1), "\n---\n")
  end)

  test("Shift-Enter, bang, and Promote use big only for their own request", function(f)
    local mentat, buffer, buf = opened(f)
    f.draft(buf, "use big once")
    f.press(buf, "<S-CR>")
    f.wait(function() return #f.sent == 1 end)
    eq(f.sent[1].model.id, "large")
    eq(f.sent[1].thinking, "max")
    eq(f.content(buf):find("large; thinking", 1, true), nil)
    assert(buffer.save_state():wait(2000))
    local saved = vim.json.decode(table.concat(vim.fn.readfile(f.root .. "/.mentat/state.json"), "\n"))
    eq(saved.pi_restore_selection, { provider = "openai", model = "reasoner", thinking = "medium" })
    f.complete(1)
    contains(f.content(buf), "## Pi\n")
    eq(f.content(buf):find("## Pi (", 1, true), nil)
    local log = table.concat(vim.fn.readfile(f.root .. "/.mentat/logs/" .. os.date("%Y-%m-%d") .. ".md"), "\n")
    contains(log, "### Pi (anthropic/large; thinking max)")
    eq(mentat.get_client().state.model.id, "reasoner")
    f.draft(buf, "normal prompt")
    f.press(buf, "<CR>")
    f.wait(function() return #f.sent == 2 end)
    f.complete(1)
    eq(f.sent[2].model.id, "reasoner")
    local session = mentat.get_session_file()
