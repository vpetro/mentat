  test("Mentat winbars remain window-local and restore editor winbars on buffer changes", function(f)
    local mentat, _, _, editor, editor_win = opened(f)
    local main_win = vim.api.nvim_get_current_win()
    contains(vim.wo.winbar, "openai/reasoner")
    vim.cmd("split")
    local copied_win = vim.api.nvim_get_current_win()
    vim.api.nvim_win_set_buf(copied_win, editor)
    f.flush()
    eq(vim.api.nvim_get_option_value("winbar", { win = copied_win, scope = "local" }), "editor winbar")
    assert(f.await(function(done) return mentat.get_client().set_model("openai", "plain", done) end))
    eq(vim.api.nvim_get_option_value("winbar", { win = editor_win, scope = "local" }), "editor winbar")
    contains(vim.api.nvim_get_option_value("winbar", { win = main_win, scope = "local" }), "openai/plain; thinking off")
    vim.api.nvim_win_set_buf(main_win, editor)
    f.flush()
    eq(vim.api.nvim_get_option_value("winbar", { win = main_win, scope = "local" }), "editor winbar")
    eq(vim.api.nvim_get_option_value("winbar", { win = copied_win, scope = "local" }), "editor winbar")
  end)
