    eq(mentat.get_client().state.model.id, "reasoner")
    eq(#f.jobs, 1)
  end)

  test("busy sends preserve drafts during preparation and retries, including later streaming", function(f)
    local mentat, _, buf = opened(f)
    f.hold.get_state = true
    f.draft(buf, "first prompt")
    f.press(buf, "<CR>")
    f.draft(buf, "next draft")
    local before = f.content(buf)
    f.press(buf, "<CR>")
    eq(f.content(buf), before)
    eq(#f.sent, 0)
    eq(mentat.get_client().is_busy(), true)
    local called = false
    vim.ui.select = function() called = true end
    vim.cmd("MentatModel")
    eq(called, false)
    f.flush()
    f.hold.get_state = nil
    assert(f.release("get_state"))
    f.wait(function() return #f.sent == 1 end)
    f.start_message(1)
    f.emit(1, { type = "tool_execution_start", toolName = "read", args = { path = "file" } })
    f.emit(1, { type = "agent_end", willRetry = true })
    f.emit(1, { type = "auto_retry_start" })
    f.emit(1, { type = "compaction_start" })
    f.flush()
    before = f.content(buf)
    f.press(buf, "<S-CR>")
    eq(f.content(buf), before)
    eq(#f.sent, 1)
    f.emit(1, { type = "compaction_end", aborted = false })
    f.text(1, "final answer")
    f.finish(1, "final answer")
    f.flush()
    contains(f.content(buf), "final answer")
    eq(f.content(buf):sub(-#"next draft"), "next draft")
    f.press(buf, "<CR>")
    f.wait(function() return #f.sent == 2 end)
    contains(f.sent[2].message, "next draft")
    eq(f.sent[2].model.id, "reasoner")
    f.complete(1)
  end)

